		<h3>Фильтрация контента</h3>
		<ul>
			<li>Отписаться от токсичных аккаунтов</li>
			<li>Ограничить бессмысленный скроллинг</li>
			<li>Сортировать подписки по категориям:
				<ul>
					<li>образовательные</li>
					<li>профессиональные</li>
					<li>творческие</li>
				</ul>
			</li>
		</ul>

		<h3>Защита сна (самое важное!)</h3>
		<p>5 золотых правил:</p>
		<ol>
			<li><strong>Цифровой закат</strong> — никаких гаджетов за 30–60 минут до сна</li>
			<li><strong>Ночной режим</strong> — фильтр синего света + тёмная тема</li>
			<li><strong>Спокойный контент</strong> — никаких драм и интенсивных игр</li>
			<li><strong>Идеальная спальня</strong> — полная темнота, отсутствие мигающих индикаторов</li>
			<li><strong>Отдельный будильник</strong> — телефон заряжается в другой комнате</li>
		</ol>

		<h3>Дополнительные советы</h3>
		<ul>
			<li>Используйте «технологические перерывы» каждые 45–60 минут работы</li>
			<li>Попробуйте «аналоговые» альтернативы:
				<ul>
					<li>бумажные книги вместо электронных</li>
					<li>настольные игры вместо мобильных</li>
				</ul>
			</li>
			<li>Введите «цифровое голодание» на 1 день в неделю</li>
		</ul>

