		<h2>Риски цифровых технологий</h2>
		<p>Современные устройства несут угрозы для:</p>
		<ul>
			<li><strong>когнитивного здоровья</strong>:
				<ul>
					<li>снижение концентрации и производительности</li>
					<li>ухудшение памяти</li>
				</ul>
			</li>
			<li><strong>психического состояния</strong>:
				<ul>
					<li>повышенный стресс и тревожность</li>
					<li>риск депрессии</li>
				</ul>
			</li>
			<li><strong>физического здоровья</strong>:
				<ul>
					<li>нарушение сна → проблемы с метаболизмом</li>
					<li>ослабление иммунитета</li>
					<li>риск болезни Альцгеймера</li>
				</ul>
			</li>
		</ul>

		<h2>4 столпа цифровой гигиены</h2>

		<h3>Контроль времени</h3>
		<ul>
			<li>Устраивать «цифровые детоксы» — полный отказ от гаджетов на определённый период</li>
			<li>Использовать приложения для учёта экранного времени</li>
			<li>Вводить «аналоговые часы» в расписании — заменять цифровые устройства аналоговыми (например, чтение бумажной книги вместо цифровой)</li>
		</ul>

		<h3>Минимизация отвлечений</h3>
