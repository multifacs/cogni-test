<p class="sm:text-xl">
	<b>Задание</b><br />
	На поле появляется цветной кружок. Отвечайте стрелкой, соответствующей его цвету: красный — влево,
	синий — вправо; в третьей части добавляются зелёный вверх и жёлтый вниз. Во второй части кружок появляется
	слева или справа — отвечайте по цвету, а не по месту.<br />

	<b>Сложность</b><br />
	Три части идут на время: 10, 30 и 60 секунд. Пробы идут непрерывно: чем быстрее отвечаете, тем больше
	проб успеете. Между частями есть экран инструкции — таймер в это время не идёт.<br />

	<b>Время</b><br />
	Отдельного лимита на пробу нет: часть заканчивается по общему таймеру. Отвечать можно стрелками на
	экране или стрелками клавиатуры.
</p>
