<p class="sm:text-xl">
	<b>Задание</b><br />
	На поле появляется цветной кружок. Отвечайте кнопкой его цвета: красный — слева, синий — справа; в третьей
	части добавляются зелёный сверху и жёлтый снизу. Во второй части кружок появляется слева или справа — нажимайте
	по цвету, а не по месту.<br />

	<b>Сложность</b><br />
	Три части: 5 проб в центре, 10 проб слева/справа и 20 проб с четырьмя цветами и позициями. Всего 35 проб.<br />

	<b>Время</b><br />
	На ответ даётся 3 секунды. Отвечать можно кнопками на экране или стрелками клавиатуры.
</p>
