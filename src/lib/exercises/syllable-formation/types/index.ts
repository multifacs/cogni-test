/**
 * Типы упражнения «Слогообразование».
 *
 * Сессия: 5 псевдословосочетаний. На каждый шаг пользователь сначала
 * придумывает ассоциацию к сочетанию, затем по ассоциации восстанавливает
 * сочетание (случайный порядок).
 */

/** Лимит времени на один шаг этапа (придумывание или восстановление). */
export const TIME_LIMIT_MS = 120_000;

/**
 * Пара псевдослов: слоги по отдельности — границы слогов нужны валидации
 * (проверка перестановок слогов в ассоциации).
 */
export type SyllablePair = {
	word1: string[];
	word2: string[];
};

export type SyllableFormationAttemptRow = {
	pairIndex: number; // 1..5
	phrase: string; // отображаемая форма: 'ба-ко-ми ло-те-су'
	association: string | null; // ассоциация пользователя; null — таймаут на этапе придумывания
	isCorrect: boolean; // восстановлено ли сочетание верно
	reactionTimeMs: number; // латентность восстановления; 120000 при таймауте
	timedOut: boolean; // таймаут на этапе восстановления
	associationMs: number; // длительность этапа придумывания; 120000 при таймауте
	// Ответ пользователя на этапе восстановления (для отображения в Result.svelte).
	// Опционально: wire-формат/БД могут не переносить его (Task 1.3).
	recalledPhrase?: string | null;
	// DB-поля опциональны (wire-формат приходит без них)
	id?: string;
	sessionId?: string;
	createdAt?: string;
};
