<p class="sm:text-xl">
	<b>Задание</b><br />
	Упражнение тренирует ассоциативную память. Вам будут показаны псевдословосочетания, составленные из
	случайных слогов.<br />

	<b>Ход</b><br />
	Вам будет последовательно показано 5 псевдословосочетаний. К каждому из них придумайте ассоциацию
	— образ, картинку или ситуацию, которая поможет запомнить сочетание. Затем, опираясь только на свои
	ассоциации, восстановите каждое сочетание. Порядок восстановления — случайный.<br />

	<b>Время</b><br />
	На придумывание каждой ассоциации даётся 2 минуты, и ещё 2 минуты — на каждое восстановление. Если
	время истечёт, шаг засчитывается как невыполненный.
