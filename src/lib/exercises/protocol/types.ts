import type { ProtocolType } from './config';
export type Stimulus = {
	[key: string]: unknown;
	displayed_words?: string[];
	feature_id?: string;
	accepted_answers_snapshot?: string[];
	displayed_token?: string;
	is_real_word?: boolean;
	lexicon_entry_id?: string;
	grid_snapshot?: string[];
	target_word?: string;
	expected_paths?: number[][];
	forced_paths?: { direction: number[]; path: number[] }[];
	allowed_directions?: number[][];
	grid_size?: number;
	target_cells?: number[];
	level?: number;
	target_count?: number;
	values_snapshot?: number[];
	locked_cell_ids?: number[];
	base_color_family?: string;
	reference_color_family?: string;
	reference_srgb?: number[];
	reference_hsl?: number[];
	base_hsl?: number[];
	option_a_hsl?: number[];
	option_b_hsl?: number[];
	option_a_srgb?: number[];
	option_b_srgb?: number[];
	correct_option?: 'A' | 'B';
	delta_param?: number;
	distance_gap?: number;
	distance_a?: number;
	distance_b?: number;
	planned_wait_ms?: number;
};
export type ProtocolEvent = {
	event_index: number;
	event_elapsed_ms: number;
	[key: string]: unknown;
};
export type ProtocolTrial = {
	trial_index: number;
	difficulty_level: number;
	stimulus: Stimulus;
	response_deadline_ms: number;
	response_time_ms: number | null;
	response_elapsed_ms: number;
	is_correct: boolean;
	is_timeout: boolean;
	response?: string | boolean | number[] | null;
	end_reason?: string;
	events: ProtocolEvent[];
	onset_offset_ms?: number;
	green_onset_ms?: number | null;
	click_onset_ms?: number | null;
	is_false_start?: boolean;
	rounds?: SumRound[];
};
export type SumRound = {
	round_index: number;
	source_cell_ids: number[];
	target_sum: number;
	solved_cell_ids: number[];
	started_offset_ms: number;
	finished_offset_ms: number | null;
	response_time_ms: number | null;
	status: 'open' | 'solved' | 'time_limit' | 'aborted';
	is_correct: boolean;
	events: ProtocolEvent[];
};
export type ProtocolPayload = { results: ProtocolTrial[]; meta: Record<string, string> };
export type StoredProtocolTrial = ProtocolTrial & {
	id?: string;
	sessionId?: string;
	createdAt?: string;
};
export type ProtocolSession = { type: ProtocolType; trials: ProtocolTrial[] };
