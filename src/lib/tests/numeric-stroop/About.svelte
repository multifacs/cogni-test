<b>Задание:</b>
<p>
	На экране появляются два числа разного размера. Цвет фона подсказывает, что именно нужно
	сравнивать.
</p>

<ul>
	<li>
		🟡 <b>Жёлтый</b> фон — отвечайте, какое число <b>крупнее на экране</b> (по размеру шрифта).
	</li>
	<li>🟢 <b>Зелёный</b> фон — отвечайте, какое число <b>больше по значению</b>.</li>
</ul>

<ul>
	<li>
		Не дайте второму признаку вас запутать: крупное число не всегда самое большое по значению, и
		наоборот.
	</li>
	<li>Ошибок можно не бояться — <b>жизней нет</b>, тест длится ровно <b>60 секунд</b>.</li>
	<li>После каждого ответа сразу появляется новая пара чисел.</li>
	<li>Отвечайте быстро.</li>
</ul>
