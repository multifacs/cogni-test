<b>Задание:</b>
<p>На экране появляются два числа разного размера.</p>

<ul>
	<li>Отвечайте, какое из них <b>крупнее на экране</b> — по размеру шрифта, а не по значению.</li>
	<li>
		Иногда крупное число совпадает по величине с бо́льшим значением, иногда — нет: не дайте
		значению числа вас запутать.
	</li>
</ul>

<ul>
	<li>Ошибок можно не бояться — <b>жизней нет</b>, тест длится ровно <b>60 секунд</b>.</li>
	<li>После каждого ответа сразу появляется новая пара чисел.</li>
	<li>Отвечайте быстро.</li>
</ul>
